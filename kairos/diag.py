"""Comprehensive diagnostic logging for KAIROS.

Tracks every step of a request:
- USER_INPUT: What the user asked (prompt / spoken command)
- LLM_PROMPT / LLM_CALL: Model invocation and parameters
- LLM_TOOL_CALL: Exactly what tool and arguments the model chose
- POLICY_CHECK: Policy evaluation (AUTO / CONFIRM / DENY)
- TOOL_START: When the tool execution begins with target device & args
- GATEWAY_SEND: Outbound command dispatched to device
- DEVICE_RESULT: Raw output returned by device (stdout, stderr, files, notifications)
- TOOL_RETURN: Output returned to the LLM context
- LLM_REPLY: Final answer generated by LLM back to user
- ERROR: Any failures, timeouts, or exceptions with stack traces
"""

import datetime
import json
import logging
import os
import sys
import threading
from collections import deque
from pathlib import Path
from typing import Any

log = logging.getLogger("kairos.diag")

# Ring buffer for live API queries
_DIAG_BUFFER: deque = deque(maxlen=1000)
_LOCK = threading.Lock()

# Persistent log file path
LOG_DIR = Path(os.getenv("KAIROS_LOG_DIR", "logs"))
LOG_FILE = LOG_DIR / "diagnostics.log"


def _ensure_log_file() -> None:
    try:
        LOG_DIR.mkdir(parents=True, exist_ok=True)
    except Exception:
        pass


def diag_log(stage: str, message: str, **details: Any) -> dict:
    """Record an exhaustive diagnostic event."""
    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
    entry = {
        "timestamp": ts,
        "stage": stage.upper(),
        "message": message,
        "details": details,
    }

    # Format for single-line console & file logging
    details_str = ""
    if details:
        try:
            details_str = " | " + json.dumps(details, default=str)
        except Exception:
            details_str = f" | {details}"

    formatted_line = f"[{ts}] [{entry['stage']:<15}] {message}{details_str}"

    with _LOCK:
        _DIAG_BUFFER.append(entry)
        try:
            _ensure_log_file()
            with open(LOG_FILE, "a", encoding="utf-8") as f:
                f.write(formatted_line + "\n")
        except Exception:
            pass

    # Also log to standard python logging so systemd / terminal captures it
    print(formatted_line, file=sys.stderr, flush=True)
    return entry


def get_diagnostic_events(limit: int = 100, stage: str | None = None) -> list[dict]:
    """Retrieve recent diagnostic events for API or inspection."""
    with _LOCK:
        events = list(_DIAG_BUFFER)
    if stage:
        target = stage.strip().upper()
        events = [e for e in events if e["stage"] == target]
    return events[-limit:]


def get_diagnostic_text(limit: int = 100) -> str:
    """Retrieve recent events as plain formatted text."""
    events = get_diagnostic_events(limit=limit)
    lines = []
    for e in events:
        det = ""
        if e.get("details"):
            try:
                det = " | " + json.dumps(e["details"], default=str)
            except Exception:
                det = f" | {e['details']}"
        lines.append(f"[{e['timestamp']}] [{e['stage']:<15}] {e['message']}{det}")
    return "\n".join(lines)


def clear_diagnostics() -> None:
    """Clear memory buffer and truncate the log file."""
    with _LOCK:
        _DIAG_BUFFER.clear()
        try:
            if LOG_FILE.exists():
                LOG_FILE.write_text("", encoding="utf-8")
        except Exception:
            pass
